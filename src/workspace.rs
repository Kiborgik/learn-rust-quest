//! The learner's working folder, `exercises/`.
//!
//! `starters/` (tracked in git) holds the pristine version of every exercise
//! and is the single source of truth. `exercises/` (git-ignored) is the
//! learner's working copy with the same relative paths; `init` creates it on
//! first run. Before a working file is overwritten, its current version is
//! saved to `.quest/backup/` (one level of undo).
//!
//! A single-file exercise is one `.rs` file. A Cargo exercise is a whole
//! package folder (`lessonNN/<dir>/`); `ex.path` is the file to open first.

use crate::exercises::{self, Exercise};
use crate::runner::{EDITION, root};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

const STARTERS: &str = "starters";
const EXERCISES: &str = "exercises";
pub const BACKUP_DIR: &str = ".quest/backup";

/// Path of an exercise relative to `exercises/` (and to `starters/`).
fn rel_path(ex: &Exercise) -> &str {
    ex.path.strip_prefix("exercises/").unwrap_or(ex.path)
}

fn starter_file(ex: &Exercise) -> PathBuf {
    root().join(STARTERS).join(rel_path(ex))
}

/// For Cargo exercises: the package folder relative to `exercises/`
/// (`lesson13/01_workshop`).
fn package_rel(ex: &Exercise) -> Option<&str> {
    if !ex.check.is_cargo() {
        return None;
    }
    let rel = rel_path(ex);
    let first = rel.find('/')?;
    let second = rel[first + 1..].find('/')? + first + 1;
    Some(&rel[..second])
}

/// Build output, lock files and test-tool leftovers (proptest failures,
/// pending insta snapshots) are never part of an exercise.
fn is_generated(path: &Path) -> bool {
    path.components().any(|c| {
        let c = c.as_os_str().to_string_lossy();
        c == "target"
            || c == "Cargo.lock"
            || c == "proptest-regressions"
            || c.ends_with(".pending-snap")
            || c.ends_with(".snap.new")
    })
}

/// All files under `dir`, relative to it (skips build output).
fn files_under(dir: &Path) -> io::Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    let mut stack = vec![PathBuf::new()];
    while let Some(rel) = stack.pop() {
        let entries = match fs::read_dir(dir.join(&rel)) {
            Ok(e) => e,
            Err(e) if e.kind() == io::ErrorKind::NotFound => continue,
            Err(e) => return Err(e),
        };
        for entry in entries {
            let entry = entry?;
            let child = rel.join(entry.file_name());
            if is_generated(&child) {
                continue;
            }
            if entry.file_type()?.is_dir() {
                stack.push(child);
            } else {
                out.push(child);
            }
        }
    }
    out.sort();
    Ok(out)
}

/// Files that make up an exercise, relative to `exercises/` and `starters/`.
fn exercise_files(ex: &Exercise) -> io::Result<Vec<PathBuf>> {
    match package_rel(ex) {
        Some(pkg) => Ok(files_under(&root().join(STARTERS).join(pkg))?
            .into_iter()
            .map(|f| Path::new(pkg).join(f))
            .collect()),
        None => Ok(vec![PathBuf::from(rel_path(ex))]),
    }
}

/// Header of the generated `exercises/Cargo.toml`.
const MANIFEST_HEADER: &str = r#"# Generated by Rust Quest from the lesson catalogue (src/lessons/). Don't edit.
# It only exists so your editor (rust-analyzer) checks each exercise file;
# the game compiles exercises itself.
[package]
name = "rust-quest-exercises"
version = "0.0.0"
edition = "{EDITION}"
publish = false
autobins = false
autoexamples = false
autotests = false
autobenches = false

[lints.rust]
dead_code = "allow"
"#;

fn editor_manifest() -> String {
    let mut s = MANIFEST_HEADER.replace("{EDITION}", EDITION);
    // Standalone workspace (not part of the game). Workshop packages are
    // members, so they share one target/ folder and one Cargo.lock.
    let mut members: Vec<&str> = exercises::all().filter_map(package_rel).collect();
    members.dedup();
    s.push_str("\n[workspace]\nresolver = \"3\"\nmembers = [");
    for m in &members {
        s.push_str(&format!("\n    \"{m}\","));
    }
    s.push_str(if members.is_empty() { "]\n" } else { "\n]\n" });
    for ex in exercises::all().filter(|ex| !ex.check.is_cargo()) {
        s.push_str(&format!(
            "\n[[bin]]\nname = \"{}\"\npath = \"{}\"\n",
            ex.id,
            rel_path(ex)
        ));
    }
    s
}

/// First-run setup, safe to call on every start. Copies the starter of every
/// exercise that doesn't exist yet (never overwrites the learner's work) and
/// keeps `exercises/Cargo.toml` in sync with the catalogue.
/// Returns how many exercise files were created.
pub fn init() -> io::Result<usize> {
    let mut created = 0;
    for ex in exercises::all() {
        for file in exercise_files(ex)? {
            let target = root().join(EXERCISES).join(&file);
            if !target.exists() {
                write(&target, &read(&root().join(STARTERS).join(&file))?)?;
                created += 1;
            }
        }
    }
    let manifest = root().join(EXERCISES).join("Cargo.toml");
    let wanted = editor_manifest();
    // Only write when it changed, so the editor doesn't reload for nothing.
    if fs::read_to_string(&manifest).ok().as_deref() != Some(wanted.as_str()) {
        write(&manifest, wanted.as_bytes())?;
    }
    Ok(created)
}

/// Like `fs::read`, but the error names the file.
fn read(path: &Path) -> io::Result<Vec<u8>> {
    fs::read(path).map_err(|e| io::Error::new(e.kind(), format!("{}: {e}", path.display())))
}

fn write(path: &Path, data: &[u8]) -> io::Result<()> {
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(path, data).map_err(|e| io::Error::new(e.kind(), format!("{}: {e}", path.display())))
}

fn backup_path(rel: &Path) -> PathBuf {
    root().join(BACKUP_DIR).join(EXERCISES).join(rel)
}

/// Puts one file back to its starter version. Returns whether it changed.
fn restore_file(rel: &Path) -> io::Result<bool> {
    let starter = read(&root().join(STARTERS).join(rel))?;
    let target = root().join(EXERCISES).join(rel);
    match fs::read(&target) {
        Ok(current) if current == starter => return Ok(false),
        Ok(current) => write(&backup_path(rel), &current)?,
        Err(e) if e.kind() == io::ErrorKind::NotFound => {}
        Err(e) => return Err(e),
    }
    write(&target, &starter)?;
    Ok(true)
}

/// Puts the starter version of one exercise back. For Cargo exercises, files
/// the learner added to the package are moved to the backup folder.
/// Returns `false` if nothing had to change.
pub fn restore(ex: &Exercise) -> io::Result<bool> {
    let wanted = exercise_files(ex)?;
    let mut changed = false;
    for rel in &wanted {
        changed |= restore_file(rel)?;
    }
    if let Some(pkg) = package_rel(ex) {
        for extra in files_under(&root().join(EXERCISES).join(pkg))? {
            let rel = Path::new(pkg).join(extra);
            if !wanted.contains(&rel) {
                let from = root().join(EXERCISES).join(&rel);
                write(&backup_path(&rel), &read(&from)?)?;
                fs::remove_file(&from)?;
                changed = true;
            }
        }
    }
    Ok(changed)
}

/// Restores every exercise. Returns how many exercises were changed.
/// Checks that all starters exist first, so a missing one changes nothing.
pub fn restore_all() -> io::Result<usize> {
    if let Some(ex) = exercises::all().find(|ex| !starter_file(ex).is_file()) {
        return Err(io::Error::new(
            io::ErrorKind::NotFound,
            format!(
                "missing starter for {}: {}",
                ex.id,
                starter_file(ex).display()
            ),
        ));
    }
    let mut changed = 0;
    for ex in exercises::all() {
        if restore(ex)? {
            changed += 1;
        }
    }
    Ok(changed)
}

// Run with `cargo test --bin quest` (plain `cargo test` also builds the
// unsolved exercises and fails).
#[cfg(test)]
mod tests {
    use super::*;

    /// Every starter must FAIL as shipped, checked exactly like the game does.
    ///
    /// Single-file starters are independent rustc runs, so they're split over
    /// all cores. Cargo starters share one target dir (and its lock), so they
    /// run one after another on a thread of their own, next to the others.
    #[test]
    #[ignore = "slow: compiles all starters; run `cargo test --bin quest -- --ignored`"]
    fn every_starter_fails_as_shipped() {
        use crate::runner::{Outcome, check_file};
        use std::sync::Mutex;
        use std::sync::atomic::{AtomicUsize, Ordering};
        assert!(
            std::process::Command::new("rustc")
                .arg("-V")
                .output()
                .is_ok(),
            "rustc not found on PATH"
        );
        let passes =
            |ex: &Exercise| matches!(check_file(ex, &starter_file(ex)), Outcome::Pass { .. });
        let (cargo, single): (Vec<&Exercise>, Vec<&Exercise>) =
            exercises::all().partition(|ex| ex.check.is_cargo());
        let passing = Mutex::new(Vec::new());
        let next = AtomicUsize::new(0);
        let workers = std::thread::available_parallelism().map_or(4, |n| n.get());
        std::thread::scope(|s| {
            s.spawn(|| {
                for ex in &cargo {
                    if passes(ex) {
                        passing.lock().unwrap().push(ex.id);
                    }
                }
            });
            for _ in 0..workers {
                s.spawn(|| {
                    while let Some(ex) = single.get(next.fetch_add(1, Ordering::Relaxed)) {
                        if passes(ex) {
                            passing.lock().unwrap().push(ex.id);
                        }
                    }
                });
            }
        });
        let passing = passing.into_inner().unwrap();
        assert!(
            passing.is_empty(),
            "starters that pass without a fix: {passing:?}"
        );
    }

    #[test]
    fn exercise_ids_are_unique() {
        // They become `[[bin]]` names in the generated manifest.
        let mut ids: Vec<&str> = exercises::all().map(|ex| ex.id).collect();
        let total = ids.len();
        ids.sort_unstable();
        ids.dedup();
        assert_eq!(ids.len(), total, "duplicate exercise id");
    }

    #[test]
    fn every_exercise_has_a_starter() {
        for ex in exercises::all() {
            assert!(
                ex.path.starts_with("exercises/"),
                "{}: odd path {}",
                ex.id,
                ex.path
            );
            let starter = starter_file(ex);
            assert!(
                starter.is_file(),
                "{}: no starter at {}",
                ex.id,
                starter.display()
            );
        }
    }
}
